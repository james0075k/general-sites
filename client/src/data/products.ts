export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p._id === id);
}

export function getFeaturedProducts(): Product[] {
  return PRODUCTS.filter((p) => p.isFeatured && p.isActive);
}

export function getNewArrivals(): Product[] {
  return PRODUCTS.filter((p) => p.isNewArrival && p.isActive);
}

export function getLowStockProducts(): Product[] {
  return PRODUCTS.filter((p) => p.stock > 0 && p.stock <= 10 && p.isActive);
}

export function getDealsOfDay(): Product[] {
  return PRODUCTS.filter((p) => p.discountPercentage >= 15 && p.isActive);
}

export function getCategories(): string[] {
  return [...new Set(PRODUCTS.map((p) => p.category))];
}
